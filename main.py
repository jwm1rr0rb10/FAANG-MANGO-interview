import hashlib
import random
import string
from collections import Counter

def get_clock_position(hash_hex: str) -> int:
    """
    Берем последние 2 знака хэша (hex), считаем сумму их значений (0-15 каждое).
    Затем переводим сумму в позицию на циферблате 1-12 по формуле:
    position = s % 12; если 0 — то 12.
    Это стандартный способ для часов. Если сумма <=9, она чаще попадает в 1-9 + 12 (как ты примерно описал "от 12 до 9").
    Если имел в виду другую формулу — скажи, поправлю.
    """
    last_two = hash_hex[-2:].upper()
    d1 = int(last_two[0], 16)
    d2 = int(last_two[1], 16)
    s = d1 + d2
    position = s % 12
    return 12 if position == 0 else position


def simulate(n: int) -> Counter:
    """Один прогон на N итераций"""
    counts = Counter()
    for _ in range(n):
        # Рандомные 6 знаков (самые обычные буквы + цифры — не важно, хэш всё равно перемешает)
        rand_str = ''.join(random.choices(string.ascii_letters + string.digits, k=6))
        
        # Самая быстрая хэш-функция в стандартной библиотеке — blake2b
        # (быстрее sha256/md5, отлично подходит под "самую быструю")
        h = hashlib.blake2b(rand_str.encode('utf-8')).hexdigest()
        
        pos = get_clock_position(h)
        counts[pos] += 1
    return counts


# ====================== ЗАПУСК ======================
print("Привет! Вот готовый скрипт. Просто скопируй и запусти.\n")

print("=== 100 000 итераций ===")
counts_100k = simulate(100_000)
for pos in range(1, 13):
    count = counts_100k[pos]
    prob = (count / 100_000) * 100
    print(f"Цифра {pos:2d}: {count:6d} раз → {prob:6.3f}%")

print("\n=== 1 000 000 итераций ===")
counts_1m = simulate(1_000_000)
for pos in range(1, 13):
    count = counts_1m[pos]
    prob = (count / 1_000_000) * 100
    print(f"Цифра {pos:2d}: {count:7d} раз → {prob:6.3f}%")

print("\nГотово! Вероятности должны быть близки к ~8.333%, но из-за суммы двух hex-цифр (треугольное распределение) будет небольшая неравномерность — именно это и интересно посчитать.")



